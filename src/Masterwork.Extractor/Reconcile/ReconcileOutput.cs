using System.Text;

namespace Masterwork.Extractor.Reconcile;

/// <summary>Renders a <see cref="Reconciliation"/> as the scenario's starting restext and its report.</summary>
public static class ReconcileOutput
{
    /// <summary>
    /// The French restext: every key that got French, in live file order under its live section
    /// comment, each with a <c># origin:</c> line. Keys without French are left out, never written in English.
    /// </summary>
    public static string Restext(Reconciliation result, string locale)
    {
        var byKey = result.Keys.Where(k => k.French is not null && k.Origin is not null).ToDictionary(k => k.Key, StringComparer.Ordinal);
        var sb = new StringBuilder();
        sb.Append("# Masterwork locale file — ").Append(locale).Append('\n');
        sb.Append("# Format: Key=Value  (one string per line)\n");
        sb.Append("# Reconciled from the official French script. Each key's \"# origin:\" is one of\n");
        sb.Append("# official | official, revised | unity, revised | agent, or draft (official French awaiting the agent pass).\n");

        // The comment block directly above a run of keys is its section heading; it's written only
        // when one of the section's keys is.
        var heading = new List<string>();
        var previousWasKey = false;
        foreach (var line in result.Layout)
        {
            if (line.Key is null)
            {
                if (previousWasKey || line.Comment!.Length == 0)
                {
                    heading.Clear();
                }

                if (line.Comment!.Length > 0)
                {
                    heading.Add(line.Comment);
                }

                previousWasKey = false;
                continue;
            }

            previousWasKey = true;
            if (!byKey.TryGetValue(line.Key, out var key))
            {
                continue;
            }

            if (heading.Count > 0)
            {
                sb.Append('\n');
                foreach (var comment in heading)
                {
                    sb.Append(comment).Append('\n');
                }

                heading.Clear();
            }

            sb.Append("# origin: ").Append(key.Origin).Append('\n');
            sb.Append(key.Key).Append('=').Append(key.French).Append('\n');
        }

        return sb.ToString();
    }

    /// <summary>Report heading for each bucket, in report order.</summary>
    public static string BucketLabel(KeyBucket bucket) => bucket switch
    {
        KeyBucket.Official => "Official",
        KeyBucket.OfficialFixed => "Official after a mechanical fix",
        KeyBucket.Conflict => "Draft for the agent: shared key worded differently",
        KeyBucket.Draft => "Draft for the agent: split or mismatch",
        KeyBucket.EnglishInFrench => "No French: English left in the French script",
        KeyBucket.Unmatched => "No French: unmatched",
        KeyBucket.NoSource => "No French: no Cradle source",
        _ => bucket.ToString(),
    };

    /// <summary>Key count per bucket, every bucket included, in report order.</summary>
    public static IReadOnlyList<(KeyBucket Bucket, int Count)> BucketCounts(Reconciliation result) =>
        Enum.GetValues<KeyBucket>().Select(b => (b, result.Keys.Count(k => k.Bucket == b))).ToList();

    /// <summary>
    /// The Markdown report: bucket counts, every key that isn't plain official with its English, French
    /// and reason, and every French-only text with the English on either side.
    /// </summary>
    public static string Report(Reconciliation result, string locale, string title)
    {
        var sb = new StringBuilder();
        var total = result.Keys.Count;
        sb.Append("# ").Append(locale).Append(" reconciliation: ").Append(title).Append("\n\n");
        sb.Append("Generated by `Masterwork.Extractor reconcile`. Official French is paired with the live English keys by passage id, then by passage structure.\n\n");

        sb.Append("## Summary\n\n| Bucket | Keys | Share |\n|---|---:|---:|\n");
        foreach (var (bucket, count) in BucketCounts(result))
        {
            sb.Append("| ").Append(BucketLabel(bucket)).Append(" | ").Append(count).Append(" | ")
              .Append((100.0 * count / Math.Max(1, total)).ToString("F1", System.Globalization.CultureInfo.InvariantCulture)).Append("% |\n");
        }

        sb.Append("| **Total** | ").Append(total).Append(" | |\n\n");
        sb.Append(result.DevNoteKeys.Count).Append(" keys used only by dev-note passages are left out of the restext and these counts.\n\n");
        sb.Append("English passages without French: ").Append(CodeList(result.EnglishPassagesWithoutFrench)).Append(".\n\n");
        sb.Append("French passages without English: ").Append(CodeList(result.FrenchPassagesWithoutEnglish)).Append(".\n\n");

        sb.Append("## Keys that aren't plain official\n");
        foreach (var bucket in Enum.GetValues<KeyBucket>().Where(b => b != KeyBucket.Official))
        {
            var keys = result.Keys.Where(k => k.Bucket == bucket).ToList();
            sb.Append("\n### ").Append(BucketLabel(bucket)).Append(" (").Append(keys.Count).Append(")\n\n");
            if (keys.Count == 0)
            {
                sb.Append("None.\n");
                continue;
            }

            sb.Append("| Key | English | French | Reason | Passages |\n|---|---|---|---|---|\n");
            foreach (var key in keys)
            {
                var french = key.French is null ? "" : Cell(key.French);
                var others = key.Candidates.Where(c => c != key.French).Select(Cell).ToList();
                if (others.Count > 0)
                {
                    french += (french.Length > 0 ? "<br>" : "") + "Also: " + string.Join("<br>Also: ", others);
                }

                sb.Append("| `").Append(key.Key).Append("` | ").Append(Cell(key.English)).Append(" | ").Append(french)
                  .Append(" | ").Append(Cell(key.Reason ?? "")).Append(" | ").Append(Cell(Abbreviate(key.Passages))).Append(" |\n");
            }
        }

        sb.Append("\n## French-only text (").Append(result.FrenchOnly.Count).Append(")\n\n");
        sb.Append("French with no English counterpart. It's dropped, never made into keys.\n\n");
        if (result.FrenchOnly.Count == 0)
        {
            sb.Append("None.\n");
        }
        else
        {
            sb.Append("| Passage | English before | French | English after |\n|---|---|---|---|\n");
            foreach (var text in result.FrenchOnly)
            {
                sb.Append("| ").Append(Cell(text.Passage)).Append(" | ").Append(Cell(text.EnglishBefore ?? "")).Append(" | ")
                  .Append(Cell(text.French)).Append(" | ").Append(Cell(text.EnglishAfter ?? "")).Append(" |\n");
            }
        }

        return sb.ToString();
    }

    private static string CodeList(IReadOnlyList<string> items) =>
        items.Count == 0 ? "none" : string.Join(", ", items.Select(i => $"`{i}`"));

    private static string Abbreviate(IReadOnlyList<string> passages) =>
        passages.Count <= 3 ? string.Join(", ", passages) : string.Join(", ", passages.Take(3)) + $", … ({passages.Count})";

    private static string Cell(string s) =>
        s.Replace("&", "&amp;", StringComparison.Ordinal)
         .Replace("<", "&lt;", StringComparison.Ordinal)
         .Replace("|", "\\|", StringComparison.Ordinal);
}
